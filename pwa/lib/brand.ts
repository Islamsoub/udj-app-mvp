/**
 * The university's logo — THE PER-UNIVERSITY SWAP POINT.
 *
 * Another university replaces the two files under public/brand/ and, if it
 * renames them, the paths below. No component names a logo file: they all read
 * these constants or the --logo-on-colour custom property.
 *
 * TWO ASSETS, NAMED BY ROLE, NOT BY SHAPE.
 *
 * - LOGO_ON_NEUTRAL — the logo as drawn, for neutral surfaces (the sidebar's
 *   --surface, the booting screen's --bg, light or dark). Rendered as a plain
 *   <img>, so it keeps its own colours: here the Unipocket tile, a
 *   #1D9E75 → #0F6E56 gradient (--jade → --jade-text in the light theme) under a
 *   white U. The tile is a graphic, not text: white on #1D9E75 is 3.39:1, which
 *   passes the 3:1 non-text threshold (WCAG 1.4.11). The hexes live in the SVG
 *   file, never in a stylesheet. A plain <img>, not next/image: next/image goes
 *   through /_next/image, which public/sw.js does not cache, so the mark would
 *   break offline. Its corners come from the artwork itself, so no consumer
 *   clips it with a border-radius — a crest or a round seal must survive intact.
 *
 * - LOGO_ON_COLOUR — the reversed logo, for coloured surfaces (the login hero's
 *   jade gradient). Used as a CSS MASK only: its shape is drawn in the
 *   --hero-mark colour, so the file's own fill does not matter, only its alpha.
 *   It should be a single silhouette with a tight viewBox, because the mask box
 *   takes its aspect ratio from it.
 *
 * WHERE EACH VALUE IS READ.
 *
 * - Components import the constants from this file. It is a plain module, not
 *   'use client', so server code may import it too.
 * - Stylesheets cannot import TypeScript. They read LOGO_ON_COLOUR through the
 *   `--logo-on-colour` custom property, declared once on :root in
 *   app/globals.css. That declaration is the second swap point: change it in
 *   step with LOGO_ON_COLOUR above.
 * - Exactly two files can read neither, and are edited by hand:
 *   - pwa/public/offline.html, its `.mark` rule. It inlines its own tokens and
 *     never loads globals.css, because the service worker serves it when
 *     nothing hashed can be relied on.
 *   - pwa/public/sw.js, PRECACHE_URLS. Both files are precached at install so
 *     the offline page and the shell still draw the logo with no network.
 *     isStaticAsset there matches the whole /brand/ folder, so a new file name
 *     under it needs no other change.
 *
 * NOT HERE: the installable app's icons (public/icons/*.png, named by
 * public/manifest.json and app/layout.tsx). They are rasters generated by
 * scripts/generate-icons.mjs from the repo-root assets/icons/Logo.svg, a
 * separate pipeline that this file does not drive.
 */

